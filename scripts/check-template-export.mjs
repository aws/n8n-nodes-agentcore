/**
 * Pre-submission check for a workflow JSON exported from the n8n editor.
 *
 * Exporting from the editor bakes in the credential IDs and names of whatever
 * credentials were attached, plus your instance ID. Those must not go into a
 * public template submission. This script reports anything that looks like real
 * instance data so it can be replaced before the file is pasted into the
 * Creator hub.
 *
 * Usage:
 *   node scripts/check-template-export.mjs <exported-workflow.json> [...]
 *
 * Exit code 1 if anything needs attention, 0 if the file looks safe.
 */

import { readFileSync } from 'node:fs';

const PLACEHOLDER_ID = /^(REPLACE_WITH|credential-id$|1$)/;
const PLACEHOLDER_INSTANCE = /^0+$/;

/** Values that are fine to ship: our own documented placeholders. */
function isPlaceholderId(id) {
	return id === undefined || id === null || PLACEHOLDER_ID.test(String(id));
}

/** Looks like a real n8n credential id: 16+ chars of base62 nanoid. */
function looksLikeRealId(id) {
	return typeof id === 'string' && /^[A-Za-z0-9]{16,}$/.test(id);
}

const files = process.argv.slice(2);
if (files.length === 0) {
	console.error('usage: node scripts/check-template-export.mjs <workflow.json> [...]');
	process.exit(2);
}

let problems = 0;

for (const file of files) {
	console.log(`\n=== ${file}`);
	let wf;
	try {
		wf = JSON.parse(readFileSync(file, 'utf8'));
	} catch (err) {
		console.log(`  INVALID JSON: ${err.message}`);
		problems++;
		continue;
	}

	const nodes = wf.nodes ?? [];
	console.log(`  nodes: ${nodes.length}`);

	// 1. Credentials
	for (const node of nodes) {
		for (const [type, cred] of Object.entries(node.credentials ?? {})) {
			const id = cred?.id;
			if (isPlaceholderId(id)) {
				console.log(`  ok        ${node.name} / ${type}: placeholder id`);
			} else {
				const why = looksLikeRealId(id) ? 'real credential id' : 'non-placeholder id';
				console.log(`  PROBLEM   ${node.name} / ${type}: ${why} "${id}"`);
				problems++;
			}
			// Credential names can carry an email address or an internal account
			// label, so a match here counts as a problem rather than a note.
			if (cred?.name && /@|\b(prod|personal|my )\b/i.test(cred.name)) {
				console.log(`  PROBLEM   ${node.name} / ${type}: credential name "${cred.name}"`);
				problems++;
			}
		}
	}

	// 2. Instance id
	const instanceId = wf.meta?.instanceId;
	if (instanceId && !PLACEHOLDER_INSTANCE.test(instanceId)) {
		console.log(`  PROBLEM   meta.instanceId is a real instance fingerprint`);
		problems++;
	}

	// 3. Execution / run data that should never ship
	for (const key of ['pinData', 'staticData']) {
		const value = wf[key];
		if (value && Object.keys(value).length > 0) {
			console.log(`  PROBLEM   ${key} is populated (contains run data)`);
			problems++;
		}
	}

	// 4. Identifiers and secrets anywhere in the document.
	const raw = JSON.stringify(wf);
	const scans = [
		[/arn:aws:[a-z0-9-]+:[a-z0-9-]+:\d{12}:/g, 'real AWS ARN with account id'],
		[/\b\d{12}\b/g, 'possible AWS account id'],
		[/\b(AKIA|ASIA|ABIA|ACCA)[A-Z0-9]{16}\b/g, 'AWS access key id'],
		// AWS secret access keys are 40 chars of base64. Require an assignment-like
		// context so ordinary long strings do not trip it.
		[
			/(?:secret|aws_secret_access_key|secretAccessKey)["'\s:=]+[A-Za-z0-9/+=]{40}\b/gi,
			'AWS secret access key',
		],
		[/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, 'email address'],
		[/\bxox[baprs]-[A-Za-z0-9-]{10,}/g, 'Slack token'],
		[/\bsk-(?:proj-|ant-)?[A-Za-z0-9_-]{20,}/g, 'OpenAI or Anthropic API key'],
		[/\bgh[pousr]_[A-Za-z0-9]{36,}/g, 'GitHub token'],
		[/\bglpat-[A-Za-z0-9_-]{20,}/g, 'GitLab token'],
		[/\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]+/g, 'JWT'],
		[/\b(?:AIza[A-Za-z0-9_-]{35})\b/g, 'Google API key'],
		[/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/g, 'private key'],
		// Long hex runs are how session tokens and signing secrets usually look.
		[/\b[a-f0-9]{40,}\b/gi, 'long hex secret'],
	];
	for (const [re, label] of scans) {
		const hits = [...new Set(raw.match(re) ?? [])];
		// Drop obvious placeholders: all-same-digit runs (0000…, 1111…) used in
		// meta.instanceId and in the synthetic webhook UUIDs these templates ship.
		const real = hits.filter((h) => !/^(\d)\1+$/.test(h));
		if (real.length > 0) {
			console.log(`  PROBLEM   ${label}: ${real.slice(0, 3).join(', ')}`);
			problems++;
		}
	}

	// 5. Webhook ids are regenerated by n8n on import, so they are safe, but a
	//    real one reveals nothing useful and is noise in a diff. Informational.
	const webhookIds = nodes.filter((n) => n.webhookId).map((n) => n.webhookId);
	if (webhookIds.length > 0) {
		console.log(`  info      ${webhookIds.length} webhookId(s) present (regenerated on import)`);
	}
}

console.log(
	problems === 0
		? '\nRESULT: no problems found. Safe to submit.'
		: `\nRESULT: ${problems} item(s) need attention before submitting.`,
);
process.exit(problems === 0 ? 0 : 1);
